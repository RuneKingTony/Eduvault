const removed = z.object({ id: z.uuid() });

const crudWithoutRemove = <
  Item extends z.ZodType,
  Create extends z.ZodType,
  Update extends z.ZodType,
>({
  base,
  item,
  create,
  update,
}: {
  base: string;
  item: Item;
  create: Create;
  update: Update;
}) => ({
  get: defineRoute({
    method: 'GET',
    path: `${base}/:id`,
    params: idParamsSchema,
    response: item,
  }),
  create: defineRoute({
    method: 'POST',
    path: base,
    body: create,
    response: item,
  }),
  update: defineRoute({
    method: 'PATCH',
    path: `${base}/:id`,
    params: idParamsSchema,
    body: update,
    response: item,
  }),
});

const crud = <
  Item extends z.ZodType,
  Create extends z.ZodType,
  Update extends z.ZodType,
>(options: {
  base: string;
  item: Item;
  create: Create;
  update: Update;
}) => ({
  ...crudWithoutRemove(options),
  remove: defineRoute({
    method: 'DELETE',
    path: `${options.base}/:id`,
    params: idParamsSchema,
    response: removed,
  }),
});

